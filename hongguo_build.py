import json, glob

def norm(t):
    return t.replace('，', ',').replace('：', ':').replace('！', '!').strip()


def find(key, pool):
    exact = key.endswith('|')
    k = norm(key.rstrip('|'))
    for t, x in pool.items():
        if (norm(t) == k) if exact else (k in norm(t)):
            return x
    raise KeyError(key)


