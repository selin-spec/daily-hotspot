def apply_fix(items):
    out = []
    for it in items:
        name = it["title_cn"] or it["title"]
        if any(k in name for k in DROP):
            continue
        for k, v in HOOK_FIX.items():
            if k in name:
                it["hook"] = v
        for k, v in HL_FIX.items():
            if k in name:
                it["highlight"] = v
        if it["highlight"].startswith("(依据剧名推断)"):
            it["highlight"] = it["highlight"][len("(依据剧名推断)"):]
            it["basis"] = "剧名推断"
            if it["adapt"] == "高":
                it["adapt"] = "中"
        else:
            it["basis"] = "剧情材料"
        if len(it["hook"]) > 30:
            print("钩子超过30字:", name, len(it["hook"]), it["hook"])
        out.append(it)
    return out

